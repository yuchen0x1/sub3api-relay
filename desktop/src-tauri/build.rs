use std::{env, fs, path::Path};

fn main() {
    let out_dir = env::var_os("OUT_DIR").expect("Cargo must provide OUT_DIR");
    let icon_path = Path::new(&out_dir).join("sub3api-cockpit-placeholder.png");

    // Tauri requires a Windows window icon even when bundling is disabled.
    // Generate a tiny original placeholder in the temporary Cargo output directory.
    const PLACEHOLDER_PNG: &[u8] = &[
        0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48,
        0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00,
        0x00, 0x1f, 0x15, 0xc4, 0x89, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x44, 0x41, 0x54,
        0x78, 0x9c, 0x63, 0x90, 0x50, 0x32, 0xfd, 0x0f, 0x00, 0x02, 0x34, 0x01, 0x6f, 0xcf,
        0x70, 0x62, 0xab, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
    ];
    fs::write(&icon_path, PLACEHOLDER_PNG).expect("write Tauri placeholder icon");

    let icon_path = icon_path.to_string_lossy().replace("\\", "/");
    println!("cargo:rustc-env=TAURI_CONFIG={{\"bundle\":{{\"icon\":[\"{}\"]}}}}", icon_path);
    println!("cargo:rerun-if-changed=tauri.conf.json");
}
